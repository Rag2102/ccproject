"""Tables for the post-freeze results (ADR-009, ADR-011, ADR-013), never by hand.

Exploratory or separately pre-registered: none of these enter the 30-comparison family, and each
caption says so. Every number is read from results/summary; nothing is recomputed here.

- costrange.tex: P4 (BAM) and P2 against never migrating (P0) at the cheap end, the assumed
  default and the dear end of the published migration-cost range, 2% budget (ADR-009).
- avoid.tex: P0+avoid against P0, P4 and P5 on seeds 2001-2050 (ADR-011).
- selective_net.tex: P4-net against P0 and P4 (family N) and P0+selective against the two
  whole-host comparators (family S), seeds 4001-4050 (ADR-013).

The paper uses the template's two-column layout, so tables span both columns with smaller type and
column gaps, and Table 3 and its P0 companion are copied from paper/tables as sideways (rotated)
tables.

Writes paper-springer/tables/{costrange,avoid,selective_net,table3,table3_p0}.tex.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUMMARY = ROOT / "results" / "summary"
OUT = ROOT / "paper-springer" / "tables"
HEADER = (
    "% generated by scripts/v2/56_paper_tables_postfreeze.py from results/summary; do not edit\n"
)


def fit(tex: str) -> str:
    """Fit a table to the two-column layout (iicol): it spans both columns at the top of a page,
    with smaller type and column gaps. sn-jnl sets the caption from the tabular inside the
    table, so the tabular must not be wrapped in a box."""
    tex = tex.replace(r"\begin{table}[t]", r"\begin{table*}[!t]").replace(
        r"\end{table}", r"\end{table*}"
    )
    return tex.replace(r"\centering\small", r"\centering\footnotesize\setlength{\tabcolsep}{3pt}")


def sideways(tex: str) -> str:
    """Table 3 and its P0 companion are too wide for portrait; the template's own answer is a
    sidewaystable (rotating, loaded in paper-springer/main.tex). Table 3's per-cell Holm p
    values still do not fit, so they move into one caption sentence read from
    confirmatory.json."""
    tex = tex.replace(
        r"\begin{table*}[t]\centering\small", r"\begin{sidewaystable*}\centering\scriptsize"
    )
    if r"$p_H$=" in tex:
        conf = load("confirmatory.json")
        ps = [c["holm_p"] for c in conf["cells"] if c.get("holm_p") is not None]
        tex = re.sub(r" \{\\scriptsize \$p_H\$=[0-9.]+\}", "", tex)
        mant, exp = f"{max(ps):.0e}".split("e")
        tex = tex.replace(
            "}\n" + r"\label{tab:main}",
            f" Holm-adjusted $p \\le {mant}\\times10^{{{int(exp)}}}$ in all {len(ps)}"
            " confirmatory cells.}\n" + r"\label{tab:main}",
            1,
        )
    return tex.replace(r"\end{table*}", r"\end{sidewaystable*}")


def load(name: str) -> dict:
    return json.loads((SUMMARY / name).read_text())


def pct(x: float, nd: int = 1) -> str:
    return f"{x:+.{nd}f}"


def with_ci(mean: float, ci: list[float]) -> str:
    return f"{pct(mean)} {{\\scriptsize [{pct(ci[0])}, {pct(ci[1])}]}}"


def costrange() -> str:
    main = load("vs_p0.json")["cells"]
    rng = load("vs_p0_costrange.json")["cells"]

    def find(cells: list[dict], regime: str, policy: str) -> dict:
        return next(
            c
            for c in cells
            if c["regime"] == regime and c["budget_pct"] == 2.0 and c["policy"] == policy
        )

    rows = []
    for reg in ("B1", "B2", "C"):
        p4 = [
            find(rng, f"{reg}@G0-low", "P4"),
            find(main, reg, "P4"),
            find(rng, f"{reg}@G0-high", "P4"),
        ]
        p2 = [find(rng, f"{reg}@G0-low", "P2"), find(rng, f"{reg}@G0-high", "P2")]
        cells = [with_ci(100 * c["saving_vs_p0_mean"], [100 * v for v in c["ci_bca"]]) for c in p4]
        cells += [pct(100 * c["saving_vs_p0_mean"]) for c in p2]
        rows.append(f"{reg} & " + " & ".join(cells) + r" \\")
    return HEADER + "\n".join(
        [
            r"\begin{table}[t]\centering\small",
            r"\caption{BAM (P4) and the tuned threshold (P2) against never migrating across the"
            r" published"
            r" migration-cost range: mean per-seed saving $(C_{P0}-C)/C_{P0}$ (\%), 95\% BCa"
            r" interval,"
            r" 2\% budget, seeds 1--30 at the two ends (assumed default: $n=50$). Exploratory"
            r" (ADR-009),"
            r" outside the confirmatory family.}",
            r"\label{tab:costrange}",
            r"\begin{tabular}{lccccc}\toprule",
            r" & \multicolumn{3}{c}{BAM (P4)} & \multicolumn{2}{c}{Threshold (P2)} \\"
            r" \cmidrule(lr){2-4}\cmidrule(lr){5-6}",
            r"Regime & Cheap end & Assumed & Expensive end & Cheap end & Expensive end \\ \midrule",
            *rows,
            r"\bottomrule\end{tabular}\end{table}",
            "",
        ]
    )


def avoid() -> str:
    prim = load("avoid_confirm.json")["primary"]
    names = {"P0": "never migrating (P0)", "P4": "BAM (P4)", "P5": "Narya-inspired (P5)"}
    rows = []
    for r in prim:
        lo, hi = (100 * v for v in r["ci_bca"]) if r.get("ci_bca") else (None, None)
        ci = "--" if lo is None else f"[{pct(lo)}, {pct(hi)}]"
        rows.append(
            f"{r['regime']} & {names[r['against']]} & {pct(100 * r['diff_mean'])} & {ci}"
            f" & {r['holm_p']:.1e} & {'yes' if r['passed'] else 'no'} \\\\"
        )
    return HEADER + "\n".join(
        [
            r"\begin{table}[t]\centering\small",
            r"\caption{Avoidance without migration (P0+avoid) against three policies on fresh seeds"
            r" 2001--2050 ($n=50$), 2\% budget, oracle predictor: mean paired difference in saving"
            r" (percentage points), 95\% BCa interval, Holm-adjusted one-sided Wilcoxon $p$. Rule"
            r" fixed"
            r" and committed before the run (ADR-011); outside the confirmatory family.}",
            r"\label{tab:avoid}",
            r"\begin{tabular}{llcccc}\toprule",
            r"Regime & Against & Difference & 95\% CI & Holm $p$ & Passed \\ \midrule",
            *rows,
            r"\bottomrule\end{tabular}\end{table}",
            "",
        ]
    )


def selective_net() -> str:
    d = load("selective_net.json")
    tab = d["table"]
    label = {
        "default": "Default costs",
        "G0-low": "Cheap migration",
        "level": "Higher cost level",
        "steep": "Steep tier weights",
    }

    def sv(reg: str, setting: str, pol: str, sigma: float = 0.0) -> dict:
        return next(
            r
            for r in tab
            if r["regime"] == reg
            and r["setting"] == setting
            and r["sigma"] == sigma
            and r["policy"] == pol
        )

    n_rows = []
    for reg in ("B1", "B2"):
        for st in ("default", "G0-low", "level", "steep"):
            p4, net = sv(reg, st, "P4"), sv(reg, st, "P4-net")
            n_rows.append(
                f"{reg} & {label[st]} & {pct(p4['saving'])} & {with_ci(net['saving'], net['ci'])}"
                f" & {int(round(p4['migrations'])):,} & {int(round(net['migrations'])):,} \\\\"
            )
        for sg in (0.5, 1.0):
            p4, net = sv(reg, "default", "P4", sg), sv(reg, "default", "P4-net", sg)
            n_rows.append(
                f"{reg} & Noise $\\sigma={sg:g}$ & {pct(p4['saving'])}"
                f" & {with_ci(net['saving'], net['ci'])}"
                f" & {int(round(p4['migrations'])):,} & {int(round(net['migrations'])):,} \\\\"
            )
    s_rows = []
    for reg in ("B1", "B2"):
        for pol, name in (
            ("P0", "Never migrating (P0)"),
            ("P0+avoid(W)", "Whole-host closing"),
            ("redirect(W)", "Redirect, no tiers"),
            ("P0+selective", "Per-tier closing"),
        ):
            r = sv(reg, "default", pol)
            sav = "0" if pol == "P0" else with_ci(r["saving"], r["ci"])
            # P0 ignores predictions, so the noise rows have no P0 entry
            noisy = "--" if pol == "P0" else pct(sv(reg, "default", pol, 1.0)["saving"])
            s_rows.append(f"{reg} & {name} & {sav} & {r['rejected']:.1f} & {noisy} \\\\")
    return HEADER + "\n".join(
        [
            r"\begin{table}[t]\centering\small",
            r"\caption{BAM that charges destination risk (P4-net) against BAM (P4): saving"
            r" against never"
            r" migrating (\%, 95\% BCa interval for P4-net) and migrations per run, seeds"
            r" 4001--4050"
            r" ($n=50$). Noise rows redraw logit noise every 30 days. Family N of ADR-013, frozen"
            r" by a"
            r" stored hash before the run; outside the confirmatory family.}",
            r"\label{tab:net}",
            r"\begin{tabular}{llcccc}\toprule",
            r"Regime & Setting & P4 & P4-net & P4 migrations & P4-net migrations \\ \midrule",
            *n_rows,
            r"\bottomrule\end{tabular}\end{table}",
            "",
            r"\begin{table}[t]\centering\small",
            r"\caption{Closing risky hosts per tier (P0+selective) against closing them to every"
            r" VM, no"
            r" migration: saving against never migrating (\%, 95\% BCa interval), rejected"
            r" arrivals per"
            r" run, and saving at noise $\sigma=1$ (redrawn every 30 days). Whole-host"
            r" comparators close"
            r" 4.4\% of hosts, the share closed by per-tier closing overall. Family S of ADR-013;"
            r" outside the confirmatory family.}",
            r"\label{tab:selective}",
            r"\begin{tabular}{llccc}\toprule",
            r"Regime & Policy & Saving & Rejected arrivals & Saving at $\sigma=1$ \\ \midrule",
            *s_rows,
            r"\bottomrule\end{tabular}\end{table}",
            "",
        ]
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in (("costrange", costrange), ("avoid", avoid), ("selective_net", selective_net)):
        (OUT / f"{name}.tex").write_text(fit(fn()))
        print(f"wrote {OUT / name}.tex")
    for name in ("table3", "table3_p0"):
        src = (ROOT / "paper" / "tables" / f"{name}.tex").read_text()
        src = sideways(src)
        (OUT / f"{name}.tex").write_text(
            f"% copied from paper/tables/{name}.tex by {Path(__file__).name}\n" + fit(src)
        )
        print(f"wrote {OUT / name}.tex")


if __name__ == "__main__":
    main()
