"""
Generates docs/openapi.yaml (task 47) from the live values webapp/core.py
actually loaded -- not hand-typed enum lists. Same reasoning as task 40's
pydantic validation checking against core.MODEL_GROUPS/CRITICALITY_MAP/
SIZE_TIERS directly rather than a hand-copied duplicate: a static spec
with hardcoded enums would silently drift out of sync the next time the
models are retrained (Backblaze publishes a new quarter, a 17th drive
model crosses the TOP_N_MODELS=15 threshold, etc.) and nobody would
notice until a client validated against the stale list. Regenerate
whenever the models change:

    python3 scripts/generate_openapi.py

The generated spec documents both deployments' actual behavior as of
today, including task 40's validation (draws its `age_days` bounds and
enum values straight from core.PredictRequest's own field constraints)
and task 41/42's architecture (both endpoints are same-origin under
whatever base URL you deploy to -- see docs/cloud_architecture.md).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "webapp"))
import core  # noqa: E402


def yaml_str_list(items, indent):
    pad = " " * indent
    return "\n".join(f"{pad}- {item!r}".replace("\'", '"').replace("'", '"') for item in items)


def build_spec():
    model_groups = yaml_str_list(core.MODEL_GROUPS, 12)
    criticality_tiers = yaml_str_list(sorted(core.CRITICALITY_MAP.keys()), 12)
    size_tiers = yaml_str_list(core.SIZE_TIERS, 12)
    which_models = yaml_str_list(list(core.WHICH_MODELS), 12)
    max_age = core.MAX_VALID_AGE_DAYS

    return f'''openapi: 3.0.3
info:
  title: VM Mitigation Policy -- Live Inference API
  description: >
    Runs one of the two trained failure-probability models (calibrated
    HistGBM or the from-scratch NumPy GQAT-Net-inspired model) live on
    caller-supplied inputs, builds a hazard/survival curve, prices a real
    migration via the Clark et al. pre-copy formula, and returns both the
    cost-sensitive policy's and the threshold baseline's decisions.
    webapp/core.py is the single source of truth both deployments below
    call into unchanged -- see docs/cloud_architecture.md.

    Generated by scripts/generate_openapi.py from the live model/data
    state -- the enums below (drive models, tiers) are read directly from
    the trained models on disk, not hand-typed, and will regenerate to
    match if the models are ever retrained.
  version: "1.0"
servers:
  - url: /
    description: >
      Relative to whatever base URL you deploy to. Render: the app's own
      domain (Flask serves both the page and the API). AWS: the
      CloudFront frontend_url (terraform output) -- /api/* is proxied
      same-origin through to API Gateway (cloud/infra/s3_frontend.tf);
      the raw API Gateway invoke_url is intentionally not callable
      directly (see cloud/infra/waf.tf).
paths:
  /api/meta:
    get:
      summary: Reference data and valid input categories
      description: >
        Everything the frontend needs to render its controls and the
        "real findings" panel -- the exact enum values /api/predict will
        accept, plus this project's already-validated headline results.
      responses:
        "200":
          description: OK
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/MetaResponse"
  /api/predict:
    post:
      summary: Run live inference + both mitigation policies on one input
      description: >
        Genuine model inference on every call (not a lookup into a
        precomputed table) -- builds a hazard curve for the requested
        drive model/age, derives time-to-failure, prices the migration,
        and returns what the cost-sensitive policy and the threshold
        baseline each decide.
      requestBody:
        required: true
        content:
          application/json:
            schema:
              $ref: "#/components/schemas/PredictRequest"
      responses:
        "200":
          description: OK
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/PredictResponse"
        "400":
          description: >
            Invalid input -- caught by webapp/core.py's PredictRequest
            validation (task 40) before any model runs. Body is
            {{"error": "invalid input", "details": [...]}}, one message
            per invalid/missing field.
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/ErrorResponse"
        "403":
          description: >
            AWS deployment only -- the raw API Gateway invoke_url was
            called directly instead of through CloudFront, which is the
            only caller carrying the required shared-secret header (see
            cloud/infra/waf.tf, cloud/api/lambda_function.py).
        "429":
          description: >
            Rate-limited -- either API Gateway's stage throttle (10 req/s
            steady-state, burst 20) or, on the AWS deployment, the WAF
            rate-based rule (2000 req/5min per source IP). See
            scripts/load_test.py for how to reproduce this deliberately.
components:
  schemas:
    PredictRequest:
      type: object
      required: [model_grp, age_days, criticality_tier, size_tier]
      properties:
        model_grp:
          type: string
          description: Real Backblaze drive model code (top {len(core.MODEL_GROUPS) - 1} by fleet count, plus OTHER).
          enum:
{model_groups}
        age_days:
          type: number
          format: float
          minimum: 0
          maximum: {max_age}
          description: Drive age in days.
        criticality_tier:
          type: string
          enum:
{criticality_tiers}
        size_tier:
          type: string
          description: Azure VM size tier (real median memory/vCPU/CPU-utilization profile per tier).
          enum:
{size_tiers}
        which_model:
          type: string
          default: histgbm
          enum:
{which_models}
    PredictResponse:
      type: object
      properties:
        model_used:
          type: string
        p_fail_within_window:
          type: number
        expected_ttf_days:
          type: number
        median_ttf_days:
          type: number
          nullable: true
        mc_dropout_std:
          type: number
          nullable: true
          description: Only set when which_model=gqat (MC-dropout uncertainty estimate).
        capacity_tb_used:
          type: number
        costs:
          type: object
          description: Real Clark et al. pre-copy migration cost, priced from the requested size_tier's actual median memory/vCPU/CPU profile.
        cost_sensitive:
          type: object
          properties:
            migrate: {{ type: boolean }}
            expected_cost_of_inaction: {{ type: number }}
            migration_cost: {{ type: number }}
            urgency_weight: {{ type: number }}
        threshold:
          type: object
          properties:
            migrate: {{ type: boolean }}
            tau: {{ type: number }}
    MetaResponse:
      type: object
      properties:
        model_groups: {{ type: array, items: {{ type: string }} }}
        size_tiers: {{ type: array, items: {{ type: string }} }}
        criticality_tiers: {{ type: array, items: {{ type: string }} }}
        tau_default: {{ type: number }}
        headline: {{ type: object }}
        comparison: {{ type: array, items: {{ type: object }} }}
        corr_sweep: {{ type: array, items: {{ type: object }} }}
        max_age_days: {{ type: integer }}
        bin_days: {{ type: integer }}
        lookahead_days: {{ type: integer }}
    ErrorResponse:
      type: object
      properties:
        error: {{ type: string }}
        details:
          type: array
          items: {{ type: string }}
'''


def main():
    spec = build_spec()
    out_path = ROOT / "docs" / "openapi.yaml"
    out_path.write_text(spec)
    print(f"Wrote {out_path} ({len(spec)} bytes) from {len(core.MODEL_GROUPS)} model groups, "
          f"{len(core.SIZE_TIERS)} size tiers, {len(core.CRITICALITY_MAP)} criticality tiers.")


if __name__ == "__main__":
    main()
